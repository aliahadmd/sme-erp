"""Generate D1's business schema from the original model metadata.

Run from the repository root:
  uv run --project api python cloudflare/scripts/generate_business_schema.py

This imports model definitions only, without the original app, configuration,
database engine or credentials. It never connects to either database.
"""

import argparse
import hashlib
import importlib
import json
import sys
from decimal import Decimal
from pathlib import Path

from sqlalchemy import (
    Boolean,
    Date,
    DateTime,
    Integer,
    Numeric,
    String,
    Text,
    UniqueConstraint,
    Uuid,
)
from sqlalchemy.dialects.postgresql import JSONB

ROOT = Path(__file__).resolve().parents[2]
PROJECT = ROOT / "cloudflare"
NOW = "(strftime('%Y-%m-%dT%H:%M:%fZ', 'now'))"


def quote(name):
    return '"' + name.replace('"', '""') + '"'


def literal(value):
    if isinstance(value, bool):
        return "1" if value else "0"
    if isinstance(value, int):
        return str(value)
    return "'" + str(value).replace("'", "''") + "'"


def shape(column):
    value = column.type
    if isinstance(value, Numeric):
        return {"kind": "decimal", "precision": value.precision, "scale": value.scale}
    if isinstance(value, Boolean):
        return {"kind": "bool"}
    if isinstance(value, Integer):
        return {"kind": "int"}
    if isinstance(value, Uuid):
        return {"kind": "uuid"}
    if isinstance(value, DateTime):
        return {"kind": "datetime"}
    if isinstance(value, Date):
        return {"kind": "date"}
    if isinstance(value, JSONB):
        return {"kind": "json"}
    if isinstance(value, String | Text):
        return {"kind": "str", "max_length": getattr(value, "length", None)}
    raise ValueError(f"Unsupported column type: {column}")


def column_default(column, info):
    if column.server_default:
        if str(column.server_default.arg) != "now()":
            raise ValueError(f"Unsupported server default: {column}")
        return {"factory": "now"}
    default = column.default
    if default is None:
        return None
    if default.is_scalar:
        return str(default.arg) if isinstance(default.arg, Decimal) else default.arg
    if default.is_callable:
        name = default.arg.__name__
        if name == "generate_uuid7":
            return {"factory": "uuid7"}
        if name in {"list", "dict"} and info["kind"] == "json":
            return {"value": [] if name == "list" else {}}
    raise ValueError(f"Unsupported Python default: {column}")


def encoded_default(info):
    value = info["default"]
    if isinstance(value, dict):
        if value.get("factory") == "now":
            return NOW
        if "value" in value:
            return literal(json.dumps(value["value"], separators=(",", ":")))
        return None  # UUIDs are generated by the command repository.
    if value is None:
        return None
    if info["kind"] == "decimal":
        # No binary float is involved in model defaults or storage.
        return str(int(Decimal(str(value)).scaleb(info["scale"])))
    return literal(value)


def column_sql(info):
    name = quote(info["name"])
    kind = info["kind"]
    storage = "INTEGER" if kind in {"decimal", "int", "bool"} else "TEXT"
    parts = [name, storage]
    if not info["nullable"]:
        parts.append("NOT NULL")
    default = encoded_default(info)
    if default is not None:
        parts.extend(["DEFAULT", default])
    condition = None
    if kind == "decimal":
        maximum = 10 ** info["precision"] - 1
        condition = f"{name} BETWEEN {-maximum} AND {maximum}"
    elif kind == "bool":
        condition = f"{name} IN (0,1)"
    elif kind == "json":
        condition = f"json_valid({name})"
    elif kind == "uuid":
        condition = f"length({name})=36"
    elif kind == "str" and info.get("max_length"):
        condition = f"length({name})<={info['max_length']}"
    if condition:
        parts.append(f"CHECK ({name} IS NULL OR ({condition}))")
    return " ".join(parts)


def render():
    sys.path.insert(0, str(ROOT / "api"))
    model_paths = sorted((ROOT / "api/app/modules").glob("*/models.py"))
    for path in model_paths:
        importlib.import_module(f"app.modules.{path.parent.name}.models")
    from app.shared.models import Base

    names = {t.fullname: f"{t.schema}_{t.name}" for t in Base.metadata.tables.values()}
    tables = []
    statements = [
        "-- Generated from the original ERP model metadata; review changes before deployment.",
        "-- Decimal columns contain scaled INTEGER coefficients, never SQLite REAL values.",
        "-- Application repositories generate UUIDv7 keys and update timestamps/revisions.",
    ]
    indexes = []
    for table in sorted(Base.metadata.tables.values(), key=lambda t: t.fullname):
        name = names[table.fullname]
        columns = []
        for column in table.columns:
            info = {"name": column.name, "nullable": column.nullable, **shape(column)}
            info["default"] = column_default(column, info)
            columns.append(info)
        primary = [c.name for c in table.primary_key]
        unique = sorted(
            {
                tuple(c.name for c in constraint.columns)
                for constraint in table.constraints
                if isinstance(constraint, UniqueConstraint)
            }
        )
        foreign = []
        for constraint in sorted(table.foreign_key_constraints, key=lambda c: c.name or ""):
            elements = list(constraint.elements)
            foreign.append(
                {
                    "columns": [e.parent.name for e in elements],
                    "table": names[elements[0].column.table.fullname],
                    "references": [e.column.name for e in elements],
                    "on_delete": constraint.ondelete or "NO ACTION",
                }
            )
        parts = [column_sql(info) for info in columns]
        parts.append(
            '"_revision" INTEGER NOT NULL DEFAULT 0 '
            'CHECK ("_revision" BETWEEN 0 AND 9007199254740991)'
        )
        parts.append("PRIMARY KEY (" + ",".join(map(quote, primary)) + ")")
        parts.extend("UNIQUE (" + ",".join(map(quote, columns)) + ")" for columns in unique)
        parts.extend(
            "FOREIGN KEY ("
            + ",".join(map(quote, f["columns"]))
            + ") REFERENCES "
            + quote(f["table"])
            + " ("
            + ",".join(map(quote, f["references"]))
            + ") ON DELETE "
            + f["on_delete"]
            for f in foreign
        )
        statements.append(
            f"CREATE TABLE {quote(name)} (\n    " + ",\n    ".join(parts) + "\n) STRICT;"
        )
        table_indexes = []
        for index in sorted(table.indexes, key=lambda i: i.name or ""):
            index_columns = [c.name for c in index.columns]
            index_name = "ix_" + name + "_" + "_".join(index_columns)
            indexes.append(
                "CREATE "
                + ("UNIQUE " if index.unique else "")
                + "INDEX "
                + quote(index_name)
                + " ON "
                + quote(name)
                + " ("
                + ",".join(map(quote, index_columns))
                + ");"
            )
            table_indexes.append({"columns": index_columns, "unique": index.unique})
        tables.append(
            {
                "legacy": table.fullname,
                "name": name,
                "columns": columns,
                "primary_key": primary,
                "unique": unique,
                "foreign_keys": foreign,
                "indexes": table_indexes,
            }
        )
    model_paths.append(ROOT / "api/app/shared/models.py")
    manifest = {
        "format": "erp-d1-schema-v1",
        "sources": {
            str(p.relative_to(ROOT)): hashlib.sha256(p.read_bytes()).hexdigest()
            for p in model_paths
        },
        "tables": tables,
    }
    return "\n\n".join([*statements, *indexes]) + "\n", json.dumps(manifest, indent=2) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    options = parser.parse_args()
    sql, manifest = render()
    outputs = {
        PROJECT / "migrations/0002_business.sql": sql,
        PROJECT / "src/erp_cf/business_schema.json": manifest,
    }
    for path, value in outputs.items():
        if options.check:
            if not path.is_file() or path.read_text() != value:
                raise SystemExit(f"Generated business schema is stale: {path.relative_to(ROOT)}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(value)
    action = "Checked" if options.check else "Generated"
    print(f"{action} {len(json.loads(manifest)['tables'])} business tables")


if __name__ == "__main__":
    main()
